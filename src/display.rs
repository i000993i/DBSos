/// Фреймбуфер через UEFI GOP (Graphics Output Protocol)
/// 32-bit BGRx (или RGBx) пиксели, 800x600 по умолчанию

use crate::driver::uart;
use uefi::boot::{self, SearchType};
use uefi::proto::console::gop::{GraphicsOutput, PixelFormat};

static mut FB_BASE: *mut u8 = core::ptr::null_mut();
static mut FB_SIZE: usize = 0;
static mut FB_WIDTH: usize = 0;
static mut FB_HEIGHT: usize = 0;
static mut FB_STRIDE: usize = 0;
static mut FB_IS_BGR: bool = true;

pub fn init() {
    let handles = match boot::locate_handle_buffer(SearchType::from_proto::<GraphicsOutput>()) {
        Ok(h) => h,
        Err(_) => { uart::write_str("[GOP] not found\r\n"); return; }
    };
    let handle = match handles.first() {
        Some(h) => *h,
        None => { uart::write_str("[GOP] no handle\r\n"); return; }
    };
    let mut gop = match boot::open_protocol_exclusive::<GraphicsOutput>(handle) {
        Ok(g) => g,
        Err(_) => { uart::write_str("[GOP] open fail\r\n"); return; }
    };

    let info = gop.current_mode_info();
    let (w, h) = info.resolution();
    let stride = info.stride();
    let pixel_format = info.pixel_format();

    uart::write_str("[GOP] ");
    uart_dec(w as u64); uart::write_str("x"); uart_dec(h as u64);
    uart::write_str(" stride="); uart_dec(stride as u64);
    match pixel_format {
        PixelFormat::Rgb => uart::write_str(" RGBx"),
        PixelFormat::Bgr => uart::write_str(" BGRx"),
        PixelFormat::Bitmask => uart::write_str(" BITMASK"),
        PixelFormat::BltOnly => uart::write_str(" BLT_ONLY"),
    }
    uart::write_str("\r\n");

    // Только 32-bit форматы
    if matches!(pixel_format, PixelFormat::BltOnly | PixelFormat::Bitmask) {
        uart::write_str("[GOP] unsupported format\r\n");
        return;
    }

    let mut fb = gop.frame_buffer();
    unsafe {
        FB_BASE = fb.as_mut_ptr();
        FB_SIZE = fb.size();
        FB_WIDTH = w;
        FB_HEIGHT = h;
        FB_STRIDE = stride;
        FB_IS_BGR = pixel_format == PixelFormat::Bgr;
    }

    uart::write_str("[GOP] FB=0x");
    uart_hex(unsafe { FB_BASE as u64 });
    uart::write_str(" sz=");
    uart_dec(unsafe { FB_SIZE as u64 });
    uart::write_str(" bytes\r\n");

    clear_screen(0x00, 0x00, 0x40); // dark blue
    draw_pixel(10, 10, 0xFF, 0x00, 0x00); // red pixel at (10,10)
    rect(50, 50, 100, 60, 0x00, 0xFF, 0x00); // green rect
    draw_char(200, 100, b'H', 0xFF, 0xFF, 0xFF);
    draw_char(210, 100, b'i', 0xFF, 0xFF, 0xFF);
    // Initialize framebuffer console
    crate::console::init(
        unsafe { FB_BASE as u64 },
        unsafe { FB_WIDTH as u32 },
        unsafe { FB_HEIGHT as u32 },
        unsafe { FB_STRIDE as u32 },
    );
}

fn pixel_offset(x: usize, y: usize) -> usize {
    (y * unsafe { FB_STRIDE } + x) * 4
}

pub fn clear_screen(r: u8, g: u8, b: u8) {
    let w = unsafe { FB_WIDTH };
    let h = unsafe { FB_HEIGHT };
    let stride = unsafe { FB_STRIDE };
    let base = unsafe { FB_BASE };
    if base.is_null() { return; }
    let is_bgr = unsafe { FB_IS_BGR };
    for y in 0..h {
        for x in 0..w {
            let off = (y * stride + x) * 4;
            unsafe {
                if is_bgr {
                    *base.add(off) = b;
                    *base.add(off + 1) = g;
                    *base.add(off + 2) = r;
                } else {
                    *base.add(off) = r;
                    *base.add(off + 1) = g;
                    *base.add(off + 2) = b;
                }
                *base.add(off + 3) = 0;
            }
        }
    }
}

pub fn draw_pixel(x: usize, y: usize, r: u8, g: u8, b: u8) {
    let base = unsafe { FB_BASE };
    let w = unsafe { FB_WIDTH };
    let h = unsafe { FB_HEIGHT };
    if base.is_null() || x >= w || y >= h { return; }
    let off = pixel_offset(x, y);
    let is_bgr = unsafe { FB_IS_BGR };
    unsafe {
        if is_bgr {
            *base.add(off) = b;
            *base.add(off + 1) = g;
            *base.add(off + 2) = r;
        } else {
            *base.add(off) = r;
            *base.add(off + 1) = g;
            *base.add(off + 2) = b;
        }
        *base.add(off + 3) = 0;
    }
}

pub fn rect(x: usize, y: usize, w: usize, h: usize, r: u8, g: u8, b: u8) {
    for dy in 0..h {
        for dx in 0..w {
            draw_pixel(x + dx, y + dy, r, g, b);
        }
    }
}

pub fn draw_char(x: usize, y: usize, ch: u8, r: u8, g: u8, b: u8) {
    // Простой 8x8 bitmap шрифт (первые 128 символов ASCII)
    if ch >= 128 { return; }
    let glyph = FONT8X8[ch as usize];
    for row in 0..8 {
        let byte = glyph[row];
        for col in 0..8 {
            if byte & (1 << (7 - col)) != 0 {
                draw_pixel(x + col, y + row, r, g, b);
            }
        }
    }
}

pub fn draw_str(x: usize, y: usize, s: &str, r: u8, g: u8, b: u8) {
    let mut cx = x;
    for &ch in s.as_bytes() {
        if ch == b'\n' || ch == b'\r' { continue; }
        draw_char(cx, y, ch, r, g, b);
        cx += 9;
        if cx + 9 >= unsafe { FB_WIDTH } { break; }
    }
}

